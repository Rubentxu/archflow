#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_key_code_indices() {
        // Verify key indices are correct and don't overlap
        assert_eq!(KeyCode::KeyA.index(), 0);
        assert_eq!(KeyCode::KeyZ.index(), 25);
        assert_eq!(KeyCode::Digit0.index(), 26);
        assert_eq!(KeyCode::Digit9.index(), 35);
        assert_eq!(KeyCode::Enter.index(), 36);
        // F12 is at index 57 (36 + 5 special + 4 arrows + 12 function keys - 1)
        assert_eq!(KeyCode::F12.index(), 57);
    }

    #[test]
    fn test_key_modifiers_bitwise() {
        // Test bitwise operations
        assert_eq!(KeyModifiers::EMPTY.0, 0);

        let shift = KeyModifiers::SHIFT;
        assert_eq!(shift.0, 0b00000001);
        assert!(shift.has_shift());
        assert!(!shift.has_control());

        let ctrl = KeyModifiers::CONTROL;
        assert_eq!(ctrl.0, 0b00000010);
        assert!(ctrl.has_control());
        assert!(!ctrl.has_shift());

        let ctrl_shift = KeyModifiers::CONTROL | KeyModifiers::SHIFT;
        assert!(ctrl_shift.has_control());
        assert!(ctrl_shift.has_shift());
        assert!(!ctrl_shift.has_alt());
        assert!(ctrl_shift.contains(KeyModifiers::CONTROL));
        assert!(ctrl_shift.contains(KeyModifiers::SHIFT));
    }

    #[test]
    fn test_key_modifiers_empty() {
        let empty = KeyModifiers::EMPTY;
        assert!(empty.is_empty());
        assert!(!empty.is_any());
        assert!(!empty.has_shift());
        assert!(!empty.has_control());
        assert!(!empty.has_alt());
        assert!(!empty.has_meta());
    }

    #[test]
    fn test_key_modifiers_all() {
        let all =
            KeyModifiers::SHIFT | KeyModifiers::CONTROL | KeyModifiers::ALT | KeyModifiers::META;
        assert!(all.is_any());
        assert!(all.has_shift());
        assert!(all.has_control());
        assert!(all.has_alt());
        assert!(all.has_meta());
    }

    #[test]
    fn test_sensor_initialization() {
        let sensor = KeyShortcutSensor::new();

        // All keys should start in released state
        assert!(!sensor.on_key_press(KeyCode::KeyA));
        assert!(!sensor.on_key_press(KeyCode::Enter));
        assert!(!sensor.on_key_press(KeyCode::Space));
    }
}
