// ArchFlow Logic - Behavior System (ECS-based)
//
// This module provides the BehaviorSystem that evaluates BehaviorBlockComponent
// entities using the ECS query API, replacing the legacy LogicMappingTable.
//
// This is the ECS-native approach to Logic Bricks evaluation:
// 1. Query all entities with BehaviorBlockComponent
// 2. Evaluate sensors for each behavior block
// 3. Execute controllers
// 4. Run actuators
//
// ═══════════════════════════════════════════════════════════════════════════════

use alloc::vec::Vec;

use archflow_core::EntityId;

use crate::ecs::component::Component;
